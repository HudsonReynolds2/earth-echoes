"""E4.5: the device-facing firmware envelope (spec 8.4; phase-4 fixed choice 3;
D166, D175).

The phase document's acceptance, one test each:

1. **A round trip that decrypts using only the KEK and the file contents**,
   standing in for what firmware does at boot.
2. **Flipping any single ciphertext byte fails GCM authentication** rather than
   yielding garbage.
3. **The plaintext PSK is provably absent from the generated bytes.**
4. **Generating the same Pod twice gives different DEKs and ciphertexts.**
5. **A missing or malformed `EOE_FIRMWARE_KEK` fails at app construction**
   with a fingerprint and never a value.

Plus the properties a firmware author will rely on: a blob moved to another
field does not authenticate (AAD binding), one DEK covers every file of one
Pod in one export, and an OPEN network's card carries no password field.
"""

import base64

import pytest
import yaml
from conftest import ephemeral_postgres, make_kek
from sqlalchemy import select

from app.config.overrides import put_overrides
from app.db import create_session_factory
from app.main import create_app
from app.models import Aggregator, Listener, Pod
from app.provisioning import envelope
from app.provisioning.envelope import EnvelopeError, FirmwareKey
from app.provisioning.generate import generate_for_pod, generate_pod_file
from app.secrets import SecretStore
from app.seed import seed_demo_hierarchy
from app.settings import Settings

pytestmark = pytest.mark.integration

PSK = "e45-planted-psk-93ac4e-the-real-wifi-password"
STREAM = "e45-planted-stream-key-17fd0b-the-real-one"

NETWORK = {
    "network.wifi_ssid": "e45-halow",
    "network.wifi_password": PSK,
    "network.stream_key": STREAM,
    "network.aggregator_ip": "10.45.0.1",
    "network.stream_endpoint": "10.45.0.1:8765/stream",
}

FIRMWARE_B64 = make_kek()
FIRMWARE = FirmwareKey.from_base64(FIRMWARE_B64, key_version=3)


@pytest.fixture(scope="module")
def env():
    with ephemeral_postgres() as url:
        _, factory = create_session_factory(url)
        store = SecretStore(factory, make_kek())
        with factory() as db:
            seed_demo_hierarchy(db)
            for pod in db.scalars(select(Pod)):
                put_overrides(db, store, "pod", str(pod.id), NETWORK)
            db.commit()
        yield factory, store, url


def _pod_ids(factory) -> list:
    with factory() as db:
        return list(
            db.scalars(
                select(Pod.id).join(Aggregator, Aggregator.pod_id == Pod.id).order_by(Pod.name)
            )
        )


def _card(factory, store, pod_id) -> bytes:
    with factory() as db:
        return generate_pod_file(db, store, pod_id, firmware_key=FIRMWARE).content


def firmware_boot(card: bytes, kek_base64: str) -> dict[str, str]:
    """Exactly what a Listener does with its card: parse, unwrap the DEK with
    the KEK baked into its firmware, unseal each field under the DEK. Nothing
    else is available to it, so nothing else is used here."""
    block = yaml.safe_load(card)["secrets"]
    assert block["format"] == envelope.ENVELOPE_FORMAT == 1
    assert block["algorithm"] == "AES-256-GCM"
    kek = FirmwareKey.from_base64(kek_base64, key_version=block["key_version"])
    dek = envelope.unwrap_dek(kek, block["wrapped_dek"])
    return {
        name: envelope.unseal(dek, f"network.{name}", block[name])
        for name in ("wifi_password", "stream_key")
        if name in block
    }


# --- 1. The firmware round trip -------------------------------------------------


def test_a_card_decrypts_with_only_the_kek_and_its_own_bytes(env):
    factory, store, _ = env
    card = _card(factory, store, _pod_ids(factory)[0])
    assert firmware_boot(card, FIRMWARE_B64) == {"wifi_password": PSK, "stream_key": STREAM}
    assert yaml.safe_load(card)["secrets"]["key_version"] == 3


def test_a_different_kek_cannot_open_the_card(env):
    factory, store, _ = env
    card = _card(factory, store, _pod_ids(factory)[0])
    with pytest.raises(EnvelopeError, match="failed authentication"):
        firmware_boot(card, make_kek())


# --- 2. Tampering fails authentication ------------------------------------------


@pytest.mark.parametrize("field", ["wifi_password", "stream_key", "wrapped_dek"])
def test_flipping_any_single_byte_fails_authentication(env, field):
    """Every byte of the blob, nonce and tag included: each flip must be
    refused, never decrypted to something else."""
    factory, store, _ = env
    card = yaml.safe_load(_card(factory, store, _pod_ids(factory)[0]))
    raw = bytearray(base64.b64decode(card["secrets"][field]))
    dek = envelope.unwrap_dek(FIRMWARE, card["secrets"]["wrapped_dek"])
    for index in range(len(raw)):
        tampered = bytearray(raw)
        tampered[index] ^= 0x01
        blob = base64.b64encode(bytes(tampered)).decode()
        with pytest.raises(EnvelopeError, match="failed authentication"):
            if field == "wrapped_dek":
                envelope.unwrap_dek(FIRMWARE, blob)
            else:
                envelope.unseal(dek, f"network.{field}", blob)


def test_a_blob_moved_to_another_field_does_not_authenticate(env):
    """The AAD binds each blob to its catalog key, so a card editor cannot
    present the stream key as the WiFi password."""
    factory, store, _ = env
    card = yaml.safe_load(_card(factory, store, _pod_ids(factory)[0]))
    dek = envelope.unwrap_dek(FIRMWARE, card["secrets"]["wrapped_dek"])
    with pytest.raises(EnvelopeError):
        envelope.unseal(dek, "network.wifi_password", card["secrets"]["stream_key"])


# --- 3. No plaintext anywhere -----------------------------------------------------


def test_the_plaintext_secrets_are_absent_from_every_generated_byte(env):
    factory, store, _ = env
    pod_id = _pod_ids(factory)[0]
    with factory() as db:
        aggregator = db.scalar(select(Aggregator).where(Aggregator.pod_id == pod_id))
        macs = frozenset(
            db.scalars(select(Listener.mac).where(Listener.aggregator_id == aggregator.id).limit(2))
        )
        files = generate_for_pod(db, store, pod_id, "mixed", macs, firmware_key=FIRMWARE)
    assert len(files) == 3
    for generated in files:
        for secret in (PSK, STREAM):
            assert secret.encode() not in generated.content
            # Not even base64-encoded plaintext: a lazy "encryption" would pass
            # the first check and fail this one.
            assert base64.b64encode(secret.encode()) not in generated.content


# --- 4. Fresh key material per export ----------------------------------------------


def test_two_exports_of_one_pod_use_different_deks_and_ciphertexts(env):
    factory, store, _ = env
    pod_id = _pod_ids(factory)[0]
    first = yaml.safe_load(_card(factory, store, pod_id))["secrets"]
    second = yaml.safe_load(_card(factory, store, pod_id))["secrets"]
    assert envelope.unwrap_dek(FIRMWARE, first["wrapped_dek"]) != envelope.unwrap_dek(
        FIRMWARE, second["wrapped_dek"]
    )
    for field in ("wrapped_dek", "wifi_password", "stream_key"):
        assert first[field] != second[field]


def test_one_export_shares_one_dek_across_a_pods_files_and_not_across_pods(env):
    factory, store, _ = env
    first_pod, second_pod = _pod_ids(factory)[:2]
    with factory() as db:
        own = generate_for_pod(db, store, first_pod, "per_listener", firmware_key=FIRMWARE)
        other = generate_for_pod(db, store, second_pod, "per_pod", firmware_key=FIRMWARE)
    deks = {
        envelope.unwrap_dek(FIRMWARE, yaml.safe_load(f.content)["secrets"]["wrapped_dek"])
        for f in own
    }
    assert len(deks) == 1, "every card of one Pod in one export unwraps to one DEK"
    other_dek = envelope.unwrap_dek(
        FIRMWARE, yaml.safe_load(other[0].content)["secrets"]["wrapped_dek"]
    )
    assert other_dek not in deks


def test_an_open_network_card_carries_no_password_field(env):
    factory, store, _ = env
    pod_id = _pod_ids(factory)[2]
    with factory() as db:
        open_network = {k: v for k, v in NETWORK.items() if k != "network.wifi_password"}
        put_overrides(
            db, store, "pod", str(pod_id), open_network | {"network.wifi_security": "OPEN"}
        )
        db.commit()
    card = _card(factory, store, pod_id)
    assert "wifi_password" not in yaml.safe_load(card)["secrets"]
    assert firmware_boot(card, FIRMWARE_B64) == {"stream_key": STREAM}


# --- 5. The KEK fails loud at app construction -------------------------------------


def _settings(url: str, firmware_kek: str | None) -> Settings:
    return Settings(
        database_url=url, session_secret="e45", kek=make_kek(), firmware_kek=firmware_kek
    )


def test_the_api_refuses_to_start_without_a_firmware_kek(env):
    _, _, url = env
    with pytest.raises(EnvelopeError, match="EOE_FIRMWARE_KEK is required"):
        create_app(_settings(url, None))


@pytest.mark.parametrize(
    ("value", "message"),
    [
        ("not base64 at all!", "not valid base64"),
        (base64.b64encode(b"\x07" * 31).decode(), "must decode to 32 bytes, got 31"),
        (base64.b64encode(b"\x07" * 33).decode(), "must decode to 32 bytes, got 33"),
    ],
)
def test_a_malformed_firmware_kek_fails_naming_the_variable_never_the_value(env, value, message):
    _, _, url = env
    with pytest.raises(EnvelopeError) as refused:
        create_app(_settings(url, value))
    text = str(refused.value)
    assert message in text
    assert "EOE_FIRMWARE_KEK" in text
    assert value not in text
    if "32 bytes" in message:
        assert "fingerprint" in text


def test_a_valid_kek_lands_on_app_state_and_never_prints(env):
    _, _, url = env
    app = create_app(_settings(url, FIRMWARE_B64))
    key = app.state.firmware_key
    assert key.key == base64.b64decode(FIRMWARE_B64)
    assert key.key_version == 1
    assert FIRMWARE_B64 not in repr(key)
    assert repr(base64.b64decode(FIRMWARE_B64)) not in repr(key)
