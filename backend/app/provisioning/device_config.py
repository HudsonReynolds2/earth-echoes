"""The on-card `device_config` file, version 1 (task E4.2; spec 5.4, 8.2, 8.3;
phase-4 fixed choice 2; DECISIONS D166).

**DRAFT pending firmware sign-off.** Spec 17 item 1 (the firmware-agreed
on-card schema) is still open. This module writes the platform's draft so
bundles can exist before that conversation ends. When the agreed schema
arrives it lands as a v2 renderer beside this one, not as an edit to it: every
card already in a tree was written in v1, and `provisioning_bundle.
template_version` records which renderer made each bundle.

## Which keys go on a card

`CARD_KEYS` is **derived from the catalog, never listed by hand**: a key
belongs on a Listener's card when it is meaningful at Pod or Listener level
(`lowest_level` ∈ pod/listener/any) and is not one of the deployment-service
keys the onboarding flow owns (`write_restricted is None`). That rule yields
exactly spec 5.4's list (MAC, name, sample rate, bit depth, capture settings,
SD buffering, log verbosity, Aggregator IP, stream endpoint) plus the Pod's
network block, which spec 8.2 says the per-pod file carries. It excludes
`listener.wake_grace_seconds` and `analysis.*` (Aggregator-side) and every
`upload.*` / `telemetry.*` / `services.*` key (post-connect only, spec 16.4).

**Secrets never appear in plaintext** (spec 5.4, 8.4). `network.wifi_password`
and `network.stream_key` reach a card only as firmware ciphertext, in a
top-level `secrets:` block built by `app.provisioning.envelope` (E4.5,
addendum PHASE4-2-02) and passed in as `sealed`. Their plaintext is dropped
even though the caller passes it, because `effective_resolved` is the
generator's only accessor. The test suite proves the drop by scanning the
output BYTES for planted values, not by reading this code.

## Shape

Nested YAML, one mapping per key group in catalog order, so a field tech reads
`network:` / `audio:` blocks rather than dotted keys. `null` is written
explicitly for a blank, because a blank is information on a per-pod card: it
says "filled in later from the cloud" (spec 8.2, 8.6). There is no timestamp
and no bundle id, so the same input renders the same bytes, which is what lets
E4.3 assert that one file serves every card in a Pod.
"""

from collections.abc import Mapping
from typing import Any

import yaml

from app.config.catalog import CATALOG, CatalogEntry
from app.provisioning.envelope import SealedSecrets

#: Bumped only by a NEW renderer. Recorded on every bundle.
TEMPLATE_VERSION = 1

#: Card-eligible levels. "any" means meaningful everywhere (D47).
_CARD_LEVELS = frozenset({"pod", "listener", "any"})


def _on_card(entry: CatalogEntry) -> bool:
    return entry.lowest_level in _CARD_LEVELS and entry.write_restricted is None


#: Every catalog key a Listener's card may carry, in catalog order. Secret keys
#: are included here because they DO belong on a card, as ciphertext (spec 8.4).
CARD_KEYS: tuple[str, ...] = tuple(entry.key for entry in CATALOG if _on_card(entry))

#: The card keys this v1 renderer writes in plaintext: all but the secrets.
PLAINTEXT_CARD_KEYS: tuple[str, ...] = tuple(
    entry.key for entry in CATALOG if _on_card(entry) and not entry.secret
)

HEADER = (
    "# Echoes of Earth device_config, schema_version 1.\n"
    "# DRAFT pending firmware sign-off (spec 17 item 1; DECISIONS D166).\n"
    "# Generated by the platform. Write this file to the card exactly as generated.\n"
)


class DeviceConfigError(ValueError):
    """The renderer was asked for a card it cannot honestly produce."""


def render_device_config_v1(
    values: Mapping[str, Any],
    *,
    blank: frozenset[str] = frozenset(),
    sealed: SealedSecrets | None = None,
) -> bytes:
    """Render one card file from a device's resolved effective config.

    `values` maps dotted catalog keys to plain values. It may hold the whole
    effective config, since keys that do not belong on a card are ignored, but
    it must hold every plaintext card key not named in `blank`. A missing key
    is an error rather than a silent `null`, because a silent `null` would be
    indistinguishable from a deliberate blank on the card.

    `blank` names card keys to write as `null` whatever `values` says: E4.3
    passes the catalog's `resolution="inventory"` keys for a per-pod file.

    `sealed` is the Pod's firmware-encrypted secrets (E4.5). It is written as
    the final top-level `secrets:` block. Every generated card carries one;
    the parameter is optional only so the plaintext part of the format can be
    tested on its own.
    """
    unknown = sorted(blank - set(PLAINTEXT_CARD_KEYS))
    if unknown:
        raise DeviceConfigError(f"cannot blank keys that are not on a v1 card: {unknown}")
    missing = sorted(key for key in PLAINTEXT_CARD_KEYS if key not in blank and key not in values)
    if missing:
        raise DeviceConfigError(f"no value for card keys: {missing}")

    document: dict[str, Any] = {"schema_version": TEMPLATE_VERSION, "template": "device_config"}
    for key in PLAINTEXT_CARD_KEYS:
        group, name = key.split(".", 1)
        document.setdefault(group, {})[name] = None if key in blank else values[key]
    if sealed is not None:
        document["secrets"] = sealed.as_block()

    body = yaml.safe_dump(
        document, sort_keys=False, default_flow_style=False, allow_unicode=True, width=1000
    )
    return (HEADER + body).encode("utf-8")
